import assert from 'node:assert/strict';
import fs from 'node:fs';
import { getProductYears, getCatalogYears, matchesProductYear } from '../src/data/catalogYears.ts';
assert.deepEqual(getProductYears('2015-2017'), ['2017','2016','2015']);
assert.deepEqual(getProductYears('2000, 2005–2007'), ['2007','2006','2005','2000']);
assert.equal(matchesProductYear('2015-2017','2016'), true);
assert.equal(matchesProductYear('2015-2017','2018'), false);
assert.equal(matchesProductYear('2015-2017','201'), false);
const products=fs.readdirSync('src/data').filter(f=>/^catalogo.*\.json$/.test(f)).flatMap(f=>JSON.parse(fs.readFileSync('src/data/'+f,'utf8')));
const years=getCatalogYears(products);
assert.equal(years[0], '2023');
assert.equal(years.at(-1), '1988');
for(const year of years) assert(products.some(p=>matchesProductYear(p.anio,year)));
const chevrolet=getCatalogYears(products.filter(p=>p.marca==='CHEVROLET'));
assert(chevrolet.includes('1995'));
assert(!chevrolet.includes('2020'));
const ford2016=products.filter(p=>p.marca==='FORD' && matchesProductYear(p.anio,'2016'));
assert(ford2016.length>0);
assert(ford2016.every(p=>p.anio==='2015-2017'));
console.log(`Filtro validado: ${years.length} años, rangos intermedios y opciones por marca.`);
