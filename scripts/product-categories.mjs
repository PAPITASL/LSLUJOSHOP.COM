import { readFileSync } from 'node:fs';
export const CATEGORIES = JSON.parse(readFileSync(new URL('../src/data/categories.json', import.meta.url), 'utf8').replace(/^\uFEFF/, ''));

export function classifyProductCategory(name) {
  const text = name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase();
  const rules = [
    [/ALTERNADOR|BATERIA|ELEVAVIDRIO|INTERRUPTOR|SWITCH|CABLE|SENSOR|MODULO|FUSIBLE|BOBINA|ARRANQUE|BOMBILLO|WINCHE|CINTA DEL TIMON/, 'ELÉCTRICO'],
    [/TABLERO|MILLARE|CONSOLA|APOYABRAZOS|RADIO|VOLANTE|TAPETE|MANIJAS? INTERIORES?|PORTAVASO|ASIENTO|PALANCA|PEDAL|VISERA|CINTURON|CARTERAS|ADAPTADOR DE ESTEREO|TIMONES/, 'INTERIOR'],
    [/^(?:KIT (?:DE )?)?(?:ALERON|SPOILER|BOMPER|BUMPER|DEFENSA|PUERTA|COMPUERTA|FRENTE)|GUARDAFANGO|GUARDABARRO|CAPOT|CAPO|COFRE|ESTRIBO|ESPEJO|MANIJA EXTERIOR|MANIJAS|BOCEL|MOLDURA|PANEL FRONTAL|SALPICADERA|LONA|PLATON|LAMEVIDRIO|VIDRIO|VALANCE/, 'CARROCERÍA'],
    [/EXPLORADORA/, 'EXPLORADORAS'],
    [/FAROLA|FARO(?:S)?\b/, 'FAROLAS'],
    [/\bSTOPS?\b|LUZ DE FRENO|LUCES TRASERAS/, 'STOPS'],
    [/PERSIANA|PARRILLA|REJILLA/, 'PERSIANAS / PARRILLAS'],
    [/LUZ|LUCES|DIRECCIONAL|COCUYO|REFLECTOR/, 'LUCES Y DIRECCIONALES'],
    [/SUSPENSION|AMORTIGUADOR|RESORTE|ROTULA|BUJE|BALANCEO|BALANCIN|BALLESTA|ESPIRALES|SEPARADORES|ESPACIADORES/, 'SUSPENSIÓN'],
    [/ESCAPE|SILENCIADOR|MOFLE|CATALIZADOR|EXOSTO/, 'ESCAPE'],
    [/EMBLEMA|LOGO|ANTENA|PROTECTOR LLUVIA|DEFLECTOR|HERRAMIENTA|ACCESORIO|DECORATIVO|EMBELLECEDOR|PORTAPLACAS|CARPA/, 'EMBLEMAS Y ACCESORIOS'],
  ];
  return rules.find(([pattern]) => pattern.test(text))?.[1] ?? 'OTROS';
}
